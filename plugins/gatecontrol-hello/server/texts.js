const langOf = (lang) => (lang === 'en' ? 'en' : 'de');

/** t(key, fallback) in `lang`; fallback undefined → the key itself. */
function translator(lang) {
  const l = langOf(lang);
  return (key, fallback) => {
    if (Object.prototype.hasOwnProperty.call(TEXTS[l], key)) return TEXTS[l][key];
    return fallback === undefined ? key : fallback;
  };
}

module.exports = { TEXTS, translator, langOf };
